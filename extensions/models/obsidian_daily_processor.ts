/**
 * @mesgme/obsidian-daily-processor — Process Superwhisper daily log entries into structured Obsidian notes
 *
 * Turn one day's daily-log note into a separate processed note that lists atomic todos and dated permanent notes (one idea each, in full sentences).
 *
 * Output: A note at <outputFolder>/<date> processed.md with the day's todos and permanent notes, plus the number of each.
 *
 * Out of scope:
 * - Extracting named entities
 * - Creating or updating topic notes
 * - Overview or summary prompts
 * - Adding tags or links between notes
 * - Editing the daily log itself
 * - Processing more than one day per run
 *
 * First draft generated by puddle draft-build from the approved
 * specification of request `obsidian-daily-processor`, with `run` filled in.
 *
 * @module
 */
