export type Result = z.infer<typeof ResultSchema>;

/** What the model pulls out of one day's log. */
export const ExtractionSchema = z.object({
  todos: z.array(z.string().min(1)),
  permanentNotes: z.array(z.object({ title: z.string().min(1), body: z.string().min(1) })),
});
export type Extraction = z.infer<typeof ExtractionSchema>;

/** OpenCode Zen's Anthropic-style Messages endpoint, which serves Claude models. */
export const MESSAGES_URL = "https://opencode.ai/zen/v1/messages";

/** Claude model that reads the log. */
export const MODEL = "claude-opus-5-5";

/** Identifies this app to OpenCode instead of a generic HTTP client. */
const USER_AGENT = "obsidian-daily-processor/2026.10.07.1";

/** JSON schema Claude's answer must match; mirrors ExtractionSchema. */
const EXTRACTION_JSON_SCHEMA = {
  type: "object",
  properties: {
    todos: { type: "array", items: { type: "string" } },
    permanentNotes: {
      type: "array",
      items: {
        type: "object",
        properties: { title: { type: "string" }, body: { type: "string" } },
        required: ["title", "body"],
        additionalProperties: false,
      },
    },
  },
  required: ["todos", "permanentNotes"],
  additionalProperties: false,
};

const SYSTEM_PROMPT = `You process one day of someone's dictated daily log from their Obsidian vault.
The log is an unstructured brain dump. Pull out exactly two things:

- todos: atomic actions the writer intends to do. One action per item, written as a short
  imperative ("Email Sam the invoice"). Split compound intentions into separate items.
  Leave out things already done and vague wishes with no action.
- permanentNotes: ideas worth keeping. One idea per note, a short title, and a body of
  full sentences that make sense on their own, without the log beside them.

Use only what the log says. Do not invent tasks or ideas. Either list may be empty.`;

/** What `run` reaches outside the vault for. Tests replace these. */
export interface Deps {
  /** Clock used when no date is given. */
  now?: () => Date;
  /** HTTP client used to reach OpenCode Zen. */
  fetch?: typeof globalThis.fetch;
}

/**
 * Turn one day's daily-log note into a separate processed note that lists atomic todos and dated permanent notes (one idea each, in full sentences).
 */
export async function run(args: RunArgs, settings: GlobalArgs, deps: Deps = {}): Promise<Processed[]> {
  const date = args.date || localDate((deps.now ?? (() => new Date()))());
  assertDate(date);
  const root = settings.vaultPath.replace(/\/+$/, "");
  const dailyFolder = insideVault(settings.dailyNotesFolder, "dailyNotesFolder");
  const outputFolder = insideVault(settings.outputFolder, "outputFolder");

  const dailyPath = `${dailyFolder}/${date}.md`;
  let log: string;
  try {
    log = await Deno.readTextFile(`${root}/${dailyPath}`);
  } catch (e) {
    if (e instanceof Deno.errors.NotFound) {
      throw new Error(`No daily note for ${date} at "${dailyPath}" in the vault.`);
    }
    throw e;
  }

  const extraction = log.trim() ? await extract(log, settings.opencodeApiKey, deps.fetch ?? globalThis.fetch) : { todos: [], permanentNotes: [] };

  const path = `${outputFolder}/${date} processed.md`;
  await Deno.mkdir(`${root}/${outputFolder}`, { recursive: true });
  await Deno.writeTextFile(`${root}/${path}`, renderNote(date, dailyPath, extraction));
  return [{ date, path, todos: extraction.todos.length, permanentNotes: extraction.permanentNotes.length }];
}

/**
 * Ask Claude, through OpenCode Zen, for the todos and permanent notes in one
 * day's log. The answer is constrained to EXTRACTION_JSON_SCHEMA and checked
 * again against ExtractionSchema before anything is written.
 */
async function extract(log: string, apiKey: string, fetch: typeof globalThis.fetch): Promise<Extraction> {
  const res = await fetch(MESSAGES_URL, {
    method: "POST",
    headers: {
      "x-api-key": apiKey,
      "anthropic-version": "2023-06-01",
      "content-type": "application/json",
      "user-agent": USER_AGENT,
    },
    body: JSON.stringify({
      model: MODEL,
      max_tokens: 16000,
      system: SYSTEM_PROMPT,
      messages: [{ role: "user", content: `<daily_log>\n${log}\n</daily_log>` }],
      output_config: { format: { type: "json_schema", schema: EXTRACTION_JSON_SCHEMA } },
    }),
  });

  const text = await res.text();
  let reply: {
    stop_reason?: string;
    content?: { type: string; text?: string }[];
    error?: { type?: string; message?: string };
  } | undefined;
  try {
    reply = JSON.parse(text);
  } catch {
    reply = undefined;
  }
  if (!res.ok) {
    const why = reply?.error?.message || text.trim() || res.statusText;
    throw new Error(`OpenCode Zen refused the request (HTTP ${res.status}): ${why} Nothing was written.`);
  }
  const answer = reply?.content?.find((c) => c.type === "text")?.text;
  if (reply?.stop_reason !== "end_turn" || answer === undefined) {
    throw new Error(`Claude gave no complete answer (stop reason: ${reply?.stop_reason ?? "unknown"}). Nothing was written.`);
  }
  return ExtractionSchema.parse(JSON.parse(answer));
}

function renderNote(date: string, dailyPath: string, x: Extraction): string {
  const todos = x.todos.length ? x.todos.map((t) => `- [ ] ${t}`).join("\n") : "None found.";
  const notes = x.permanentNotes.length
    ? x.permanentNotes.map((n) => `### ${n.title}\n\n*${date}*\n\n${n.body}`).join("\n\n")
    : "None found.";
  return `# ${date} processed\n\nFrom the daily log \`${dailyPath}\`.\n\n## Todos\n\n${todos}\n\n## Permanent notes\n\n${notes}\n`;
}

/** YYYY-MM-DD of `d` in the machine's local time zone. */
function localDate(d: Date): string {
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

function assertDate(date: string): void {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(date);
  const d = m && new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]));
  if (!m || !d || localDate(d) !== date) {
    throw new Error(`The date must be a real day written as YYYY-MM-DD, not "${date}".`);
  }
}

/** A setting's folder, trimmed of slashes, refused if it points outside the vault. */
function insideVault(folder: string, setting: string): string {
  const f = folder.replace(/\/+$/, "");
  if (f.startsWith("/") || f.split("/").includes("..")) {
    throw new Error(`${setting} must be a folder inside the vault, not "${folder}".`);
  }
  return f;
}

